#!/usr/bin/env python3
"""gen-variant-workflow.py [PARTS]: write .github/workflows/variant.yml.

One variant of the browser is built by a chain of up to PARTS jobs (GitHub-hosted jobs stop after 6 hours). Each job
restores the source, sysroot and the previous job's build folder, runs source/container/build.sh for HOURS, and
hands the build folder on as an artifact. The job that finishes the build uploads browser.tar.zst; the package job
makes the IPK and its build provenance attestation. Edit this script, not variant.yml.
"""
import os
import sys

PARTS = int(sys.argv[1]) if len(sys.argv) > 1 else 14
B = "/home/runner/cnci"
OUTSNAP = "out-tv-official-compat"

head = f"""# GENERATED by ci/gen-variant-workflow.py ({PARTS} parts). Do not edit by hand.
name: Build one variant
on:
  workflow_call:
    inputs:
      source_repo: {{ type: string, required: true }}
      sha: {{ type: string, required: true }}
      variant: {{ type: string, required: true }}
      version: {{ type: string, required: true }}
      hours: {{ type: string, required: true }}
permissions:
  contents: read
jobs:
"""


def part(n):
    p = f"part_{n:02d}"
    prev = f"part_{n - 1:02d}"
    lines = [f"  {p}:", f"    name: Build part {n}"]
    if n > 1:
        lines += [f"    needs: {prev}", f"    if: needs.{prev}.outputs.status == 'running'"]
    lines += [
        "    runs-on: ubuntu-24.04",
        "    timeout-minutes: 355",
        "    env:",
        f"      BUILD_ID: ci-${{{{ github.run_id }}}}-${{{{ inputs.variant }}}}-p{n:02d}",
        "    outputs:",
        "      status: ${{ steps.st.outputs.status }}",
        "    steps:",
        "      - uses: actions/checkout@v4",
        "      - id: prep",
        "        uses: ./.github/actions/prepare",
        "        with: { source_repo: \"${{ inputs.source_repo }}\", sha: \"${{ inputs.sha }}\", variant: \"${{ inputs.variant }}\", swap_gb: \"12\" }",
        "      - name: Restore the source snapshot",
        "        uses: actions/cache/restore@v4",
        f"        with: {{ key: \"${{{{ steps.prep.outputs.src_key }}}}\", fail-on-cache-miss: true, path: \"{B}/vol/snap/src.tar.zst\\n{B}/vol/snap/src.json\" }}",
        "      - name: Restore sysroot and builtins",
        "        uses: actions/cache/restore@v4",
        f"        with: {{ key: \"${{{{ steps.prep.outputs.tools_key }}}}\", fail-on-cache-miss: true, path: \"{B}/vol/snap/sysroot-compat.tar.zst\\n{B}/vol/snap/sysroot-compat.json\\n{B}/vol/snap/builtins.tar.zst\\n{B}/vol/snap/builtins.json\" }}",
        "      - name: Restore NSS/NSPR",
        "        uses: actions/cache/restore@v4",
        f"        with: {{ key: \"${{{{ steps.prep.outputs.nss_key }}}}\", fail-on-cache-miss: true, path: \"{B}/nss\" }}",
        f"      - run: cp {B}/nss/nss.tar.zst {B}/vol/artifacts/nss/",
    ]
    if n > 1:
        lines += [
            "      - name: Build folder from the previous part",
            "        uses: actions/download-artifact@v4",
            f"        with: {{ name: \"out-${{{{ inputs.variant }}}}\", path: \"{B}/vol/snap\" }}",
        ]
    lines += [
        "      - name: Build (build.sh)",
        "        env: { BUILD_JOBS: \"4\", CCACHE_SAVE_MIN: \"1000000\" }",
        "        run: bash ci/crun.sh build.sh chrome \"${{ inputs.hours }}\" 600 0 1",
        "      - id: st",
        "        name: Result of this part",
        f"        run: bash ci/part-status.sh {n} {PARTS}",
        "      - name: Hand the build folder to the next part",
        "        if: steps.st.outputs.status == 'running'",
        "        uses: actions/upload-artifact@v4",
        "        with:",
        "          name: out-${{ inputs.variant }}",
        f"          path: \"{B}/vol/snap/{OUTSNAP}.tar.zst\\n{B}/vol/snap/{OUTSNAP}.json\\n{B}/vol/snap/patch-state.json\"",
        "          overwrite: true",
        "          retention-days: 3",
        "          compression-level: 0",
        "      - name: Browser",
        "        if: steps.st.outputs.status == 'completed'",
        "        uses: actions/upload-artifact@v4",
        "        with:",
        "          name: browser-${{ inputs.variant }}",
        f"          path: \"{B}/vol/artifacts/${{{{ env.BUILD_ID }}}}/\"",
        "          retention-days: 14",
        "          compression-level: 0",
        "      - name: Logs",
        "        if: always()",
        "        uses: actions/upload-artifact@v4",
        "        with:",
        f"          name: logs-${{{{ inputs.variant }}}}-p{n:02d}",
        f"          path: \"{B}/vol/logs/\"",
        "          retention-days: 14",
        "          if-no-files-found: ignore",
        "",
    ]
    return "\n".join(lines)


needs = ", ".join(f"part_{n:02d}" for n in range(1, PARTS + 1))
package = f"""  package:
    name: IPK and provenance
    needs: [{needs}]
    if: always() && contains(needs.*.outputs.status, 'completed')
    runs-on: ubuntu-24.04
    permissions:
      contents: read
      id-token: write
      attestations: write
    steps:
      - uses: actions/checkout@v4
      - id: prep
        uses: ./.github/actions/prepare
        with: {{ source_repo: "${{{{ inputs.source_repo }}}}", sha: "${{{{ inputs.sha }}}}", variant: "${{{{ inputs.variant }}}}", docker: "false" }}
      - name: Restore NSS/NSPR
        uses: actions/cache/restore@v4
        with: {{ key: "${{{{ steps.prep.outputs.nss_key }}}}", fail-on-cache-miss: true, path: "{B}/nss" }}
      - uses: actions/download-artifact@v4
        with: {{ name: "browser-${{{{ inputs.variant }}}}", path: browser }}
      - uses: actions/download-artifact@v4
        with: {{ name: launcher, path: launcher }}
      - name: Make the IPK (package/mkipk.py)
        run: bash ci/package.sh "${{{{ inputs.variant }}}}" "${{{{ inputs.version }}}}" "${{{{ inputs.source_repo }}}}" "${{{{ inputs.sha }}}}"
      - name: Build provenance attestation
        uses: actions/attest-build-provenance@v2
        with:
          subject-path: |
            ipk/*.ipk
            browser/browser.tar.zst
            launcher/cnrun
      - uses: actions/upload-artifact@v4
        with: {{ name: "ipk-${{{{ inputs.variant }}}}", path: ipk/, retention-days: 30, compression-level: 0 }}
"""

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".github", "workflows", "variant.yml")
with open(out, "w") as f:
    f.write(head + "\n".join(part(n) for n in range(1, PARTS + 1)) + package)
print("wrote", os.path.normpath(out))
